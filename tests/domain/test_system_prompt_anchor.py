"""Tests for system-prompt generation and persistence (v3.0.0 B3).

The system prompt is generated by the input generator at run time and stored in
``messages[0]`` — the array is the single source of truth (D1).  These tests
pin the behaviour at the three places it can go wrong: generation, message
placement, and the persistence gate.
"""

from __future__ import annotations

import json
import struct
import zlib
from pathlib import Path
from typing import Any
from unittest.mock import MagicMock

from ard.backends.api_client import (
    ARDEmptyContentError,
    ChatAPIClient,
    ChatAPIStats,
    ChatResponse,
)
from ard.core.system_prompt import SYSTEM_PROMPT_NONE
from ard.core.types import AnchorSpec, DataSource, TurnSpec
from ard.domain.anchor_shape import message_shape_error
from ard.domain.bank import AppendOutcome, append_anchor, read_anchor_bank
from ard.domain.text_anchor import AnchorGenerationStats, generate_text_anchors

SYSTEM_TEXT = "You are a meticulous Python debugger for legacy SQL pipelines."
ANSWER = "The bug is in the join predicate."
REASONING = "Check the join keys, then the filter."


def _spec(mode: str, spec_id: str = "sys_001") -> AnchorSpec:
    """A single-turn spec whose metadata carries *mode*."""
    return AnchorSpec(
        id=spec_id,
        anchor_meta={
            "language": "English",
            "knowledge_domain": "software_engineering",
            "capability": "debugging",
            "conversation_type": "single_turn",
            "system_prompt_mode": mode,
        },
        turns=[
            TurnSpec(
                turn_index=0,
                role="user",
                generation_instruction="Ask about a failing SQL query",
                is_final=True,
            )
        ],
        input_generator_id="input-gen",
    )


def _input_client(system_text: str = SYSTEM_TEXT) -> MagicMock:
    """Input-generator double whose first reply is the system prompt."""
    client = MagicMock(spec=ChatAPIClient)
    client.chat.side_effect = [
        ChatResponse(content=system_text),
        ChatResponse(content="Why does my SQL query return duplicates?"),
    ]
    return client


def _input_client_for_none() -> MagicMock:
    """Input-generator double for a mode-``none`` anchor (one call: the question)."""
    client = MagicMock(spec=ChatAPIClient)
    client.chat.return_value = ChatResponse(content="Why is my query slow?")
    return client


def _target_client() -> MagicMock:
    client = MagicMock(spec=ChatAPIClient)
    client.chat.return_value = ChatResponse(content=ANSWER, reasoning=REASONING)
    return client


def _generate(spec: AnchorSpec, input_client: MagicMock, target_client: MagicMock):
    return generate_text_anchors(
        specs=[spec],
        input_client=input_client,
        target_client=target_client,
        input_model_name="input-model",
        target_model_name="target-model",
        concurrency=1,
        disable_progress=True,
    )


# ── Generation ──────────────────────────────────────────────────────────────


def test_present_mode_prepends_the_generated_system_message() -> None:
    """A styled anchor carries its generated system text at ``messages[0]``."""
    results = _generate(_spec("task_constraint"), _input_client(), _target_client())

    assert len(results) == 1
    messages = results[0].messages
    assert [message["role"] for message in messages] == ["system", "user"]
    assert messages[0]["content"] == SYSTEM_TEXT
    assert message_shape_error(messages) is None


def test_absent_mode_adds_no_system_message() -> None:
    """``none`` behaves exactly like the pre-B3 shape (no system message)."""
    input_client = MagicMock(spec=ChatAPIClient)
    input_client.chat.return_value = ChatResponse(content="Why is my query slow?")

    results = _generate(_spec(SYSTEM_PROMPT_NONE), input_client, _target_client())

    assert len(results) == 1
    messages = results[0].messages
    assert [message["role"] for message in messages] == ["user"]
    # Exactly one input-generator call: no system prompt was requested.
    assert input_client.chat.call_count == 1


def test_system_prompt_is_generated_from_the_anchor_metadata() -> None:
    """The system-prompt request names the anchor's own domain and capability."""
    input_client = _input_client()
    _generate(_spec("domain_style"), input_client, _target_client())

    first_call_messages = input_client.chat.call_args_list[0].args[0]
    prompt_text = "\n".join(message["content"] for message in first_call_messages)
    assert "software_engineering" in prompt_text
    assert "debugging" in prompt_text
    assert "domain-style" in prompt_text


def test_target_model_sees_the_system_message() -> None:
    """The teacher answers with the system prompt in its prefix (scheme §3.3)."""
    target_client = _target_client()
    _generate(_spec("minimal_persona"), _input_client(), target_client)

    messages_sent_to_teacher = target_client.chat.call_args.args[0]
    assert messages_sent_to_teacher[0]["role"] == "system"
    assert messages_sent_to_teacher[0]["content"] == SYSTEM_TEXT


def test_unknown_mode_is_rejected() -> None:
    """An unknown mode is a vocabulary violation, not a silent no-system anchor.

    The scheduler catches per-anchor failures and classifies them
    (:func:`~ard.domain.text_anchor.failure_reason`), so the observable effect
    is an anchor abandoned under ``unexpected_error`` — deliberately *not* one
    of the server/model-output buckets, so a vocabulary bug can never be
    mistaken for load or for a model quirk.
    """
    stats = AnchorGenerationStats()
    results = generate_text_anchors(
        specs=[_spec("casual_vibes")],
        input_client=_input_client(),
        target_client=_target_client(),
        input_model_name="input-model",
        target_model_name="target-model",
        concurrency=1,
        disable_progress=True,
        stats=stats,
    )

    assert results == []
    assert stats.abandoned_by_reason == {"unexpected_error": 1}


def test_empty_system_prompt_abandons_the_anchor() -> None:
    """No system text means no anchor — never a style-less system message."""
    results = _generate(_spec("detailed_persona"), _input_client("   "), _target_client())

    # The empty system prompt is classified as a model-output failure by the
    # scheduler (`failure_reason`), so the run returns no anchor instead of a
    # record that claims a style it does not carry.
    assert results == []


# ── Persistence ─────────────────────────────────────────────────────────────


def test_system_message_survives_the_persistence_gate(tmp_path: Path) -> None:
    """The generated system message is what lands in the bank."""
    results = _generate(_spec("task_constraint"), _input_client(), _target_client())
    anchor = results[0]

    bank = tmp_path / "anchor_bank.jsonl"
    assert append_anchor(anchor, bank) is AppendOutcome.APPENDED

    records = read_anchor_bank(bank)
    assert len(records) == 1
    record = records[0]
    assert [message["role"] for message in record["messages"]] == ["system", "user"]
    assert record["messages"][0]["content"] == SYSTEM_TEXT
    assert "system_prompt" not in record  # D1: messages are the only truth
    assert record["anchor_meta"]["system_prompt_mode"] == "task_constraint"
    assert record["data_source"] == "ard_text"


