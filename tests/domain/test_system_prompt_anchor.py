def test_anchor_data_source_reads_image_parts() -> None:
    """Both persisted image forms count; text-only and non-image parts do not.

    Two forms are accepted, and they are accepted for different reasons:

    * ``{"type": "image", "image": "images/x.jpg"}`` — the rewritten form that
      ``_convert_images_to_paths`` writes for every anchor, in the default run
      *and* in a ``--no-convert`` run (that flag only decides whether image
      *files* are transcoded when copied into the output directory; it never
      touches message parts);
    * ``{"type": "image_url", "image_url": {"url": "data:image/jpeg;base64,…"}}``
      — the API's inline form.  It is **not** an expected persisted form: it
      reaches the bank only through a writer bug, and it did reach it once.  It
      is still matched, because the routing rule must describe the *record*
      rather than the writer's current habits — a rule that only accepts today's
      shape goes quiet the moment the writer changes again.

    Missing the second form is what made the B3 verification run label every
    image anchor ``ard_text`` — the inline form was the only one that run
    produced, and the function matched only ``image``.  Missing the *first* form
    is the symmetric failure: those records would be split off as text-only.
    """
    from ard.domain.text_anchor import anchor_data_source

    assert anchor_data_source([{"role": "user", "content": "plain"}]) is DataSource.ARD_TEXT

    assert (
        anchor_data_source(
            [
                {"role": "user", "content": "plain"},
                {
                    "role": "user",
                    "content": [
                        {"type": "image", "image": "images/x.jpg"},
                        {"type": "text", "text": "what is this?"},
                    ],
                },
            ]
        )
        is DataSource.ARD_MULTI
    )
    assert (
        anchor_data_source(
            [
                {
                    "role": "user",
                    "content": [
                        {"type": "image_url", "image_url": {"url": "data:image/jpeg;base64,AAAA"}},
                        {"type": "text", "text": "what is this?"},
                    ],
                }
            ]
        )
        is DataSource.ARD_MULTI
    )
    # A text-only part list stays text, even though it is a list.
    assert (
        anchor_data_source(
            [{"role": "user", "content": [{"type": "text", "text": "no image here"}]}]
        )
        is DataSource.ARD_TEXT
    )


# ── Image handling end-to-end (real conversion path, leading system included) ─
#
# The tests above pin the routing *function*; the three below pin the *pipeline*,
# because these are the two paths that a green unit test cannot vouch for.  An
# earlier version of this file covered the inline form by patching
# ``_convert_images_to_paths`` into an identity function, which is the one thing
# that must never be done here: the patch *manufactured* the inline form the test
# then asserted, so it stayed green while the real pipeline kept base64 in every
# anchor that carried a system prompt.  These tests therefore run the unpatched
# pipeline and assert on what the bank would actually contain.


def _image_spec_meta(mode: str) -> dict[str, str]:
    """Anchor metadata for a single-turn image anchor in the given mode."""
    return {
        "language": "English",
        "knowledge_domain": "vision",
        "capability": "qa",
        "conversation_type": "single_turn",
        "system_prompt_mode": mode,
    }


def test_no_convert_run_routes_image_anchor_to_ard_multi(tmp_path: Path) -> None:
    """Legacy inline records still route to ``ard_multi`` (no conversion run).

    ``_convert_images_to_paths`` is not called at all here, which is the closest
    local stand-in for a run whose conversion step is bypassed — the state that
    produced the pre-fix inline records.  The point is the routing rule, not the
    conversion: such a record plainly carries an image and must not be filed as
    text-only (W-1 / §1.4).

    Note the asymmetry with the end-to-end test below: **this input can no longer
    be produced by the pipeline itself.**  It is kept as a guard for records
    written before the alignment fix.
    """
    from ard.domain.text_anchor import _convert_images_to_paths

    images_dir = tmp_path / "images"
    images_dir.mkdir()
    png = _create_minimal_png(images_dir)
    inline: dict[str, Any] = {
        "role": "user",
        "content": [
            {"type": "text", "text": "What do you see?"},
            {"type": "image_url", "image_url": {"url": "data:image/jpeg;base64,AAAA"}},
        ],
    }
    spec = AnchorSpec(
        id="img_nowriter",
        anchor_meta=_image_spec_meta(SYSTEM_PROMPT_NONE),
        turns=[
            TurnSpec(
                turn_index=0,
                role="user",
                generation_instruction="Describe this image",
                image_path=str(png),
                is_final=True,
            )
        ],
    )

    # The pre-fix record shape, built by hand instead of by patching the helper:
    # converting it would rewrite the part, so the inline form only survives if
    # the conversion step is not run at all.
    passed_through = [inline]
    assert passed_through[0]["content"][1]["type"] == "image_url"
    assert _convert_images_to_paths(passed_through, spec)[0]["content"][1] == {
        "type": "image",
        "image": "images/probe.png",
    }, "the helper must rewrite image_url parts into the referenced-path form"

    from ard.domain.text_anchor import anchor_data_source

    assert anchor_data_source(passed_through) is DataSource.ARD_MULTI

    results = _generate(spec, _input_client_for_none(), _target_client())
    assert len(results) == 1
    anchor = results[0]

    # By the time a real run persists its anchor, the inline form is gone: the
    # turn that owns the image is matched through the leading-system offset.
    persisted_types = [
        part.get("type")
        for message in anchor.messages
        for part in (message["content"] if isinstance(message["content"], list) else [])
    ]
    assert "image_url" not in persisted_types, persisted_types
    assert "image" in persisted_types, persisted_types
    assert anchor.data_source is DataSource.ARD_MULTI

    bank = tmp_path / "noinline_bank.jsonl"
    assert append_anchor(anchor, bank) is AppendOutcome.APPENDED
    assert read_anchor_bank(bank)[0]["data_source"] == "ard_multi"


def test_pipeline_with_system_prompt_converts_image_to_a_path(tmp_path: Path) -> None:
    """A leading ``system`` message must not stop the image from being rewritten.

    This is the regression test for the alignment defect: message *i* was paired
    with ``spec.turns[i]``, so once the generated system prompt occupied
    ``messages[0]``, the image-owning turn 0 was looked up as ``turns[1]`` — a
    turn without an ``image_path`` — and the rewrite was skipped.  Every anchor
    with a system prompt (i.e. the whole B3 feature) therefore persisted its
    image as an inline base64 data URI, which also contradicted
    ``test_integration.py``'s ``assert "image_url" not in json.dumps(messages)``.

    The system message is real here (``task_constraint`` mode, generated by the
    input-generator double), so the offset exists exactly as it does in a run.
    """
    images_dir = tmp_path / "images"
    images_dir.mkdir()
    png = _create_minimal_png(images_dir)
    spec = AnchorSpec(
        id="img_with_system",
        anchor_meta=_image_spec_meta("task_constraint"),
        turns=[
            TurnSpec(
                turn_index=0,
                role="user",
                generation_instruction="Describe this image",
                image_path=str(png),
                is_final=True,
            )
        ],
    )
    input_client = _input_client()  # first call = the system prompt, then the question

    results = _generate(spec, input_client, _target_client())

    assert len(results) == 1
    anchor = results[0]
    assert [m["role"] for m in anchor.messages] == ["system", "user"]

    persisted_types = [
        part.get("type")
        for message in anchor.messages
        for part in (message["content"] if isinstance(message["content"], list) else [])
    ]
    assert "image" in persisted_types, persisted_types
    assert "image_url" not in persisted_types, persisted_types
    assert "base64" not in json.dumps(anchor.messages)
    assert anchor.data_source is DataSource.ARD_MULTI

    bank = tmp_path / "sys_image_bank.jsonl"
    assert append_anchor(anchor, bank) is AppendOutcome.APPENDED
    record = read_anchor_bank(bank)[0]
    assert record["data_source"] == "ard_multi"

    image_paths = [
        part["image"]
        for message in record["messages"]
        for part in (message["content"] if isinstance(message["content"], list) else [])
        if isinstance(part, dict) and part.get("type") == "image"
    ]
    assert image_paths == ["images/probe.png"], image_paths


def test_multiturn_image_paths_stay_aligned_behind_a_system_prompt(tmp_path: Path) -> None:
    """Two images on two turns each keep *their own* path with a system prompt.

    ``test_integration.py::test_image_paths_stay_aligned_with_their_turns``
    guards the same invariant without a system prompt, which is exactly why the
    offset defect slipped past it: its spec never has a ``system_prompt_mode``,
    so the 1:1 assumption held.  With the leading system in place, a fix that
    shifted the pairing instead of removing it would swap the two paths — this
    test fails on that, not just on a leaked base64.
    """
    images_dir = tmp_path / "images"
    images_dir.mkdir()
    first = _create_minimal_png(images_dir, "first.png")
    second = _create_minimal_png(images_dir, "second.png")

    spec = AnchorSpec(
        id="img_alignment_system",
        anchor_meta={
            "language": "English",
            "knowledge_domain": "vision",
            "capability": "description",
            "conversation_type": "multi_turn",
            "system_prompt_mode": "minimal_persona",
        },
        turns=[
            TurnSpec(
                turn_index=0,
                role="user",
                generation_instruction="Describe this image",
                image_path=str(first),
            ),
            TurnSpec(turn_index=1, role="assistant", generation_instruction="Respond"),
            TurnSpec(
                turn_index=2,
                role="user",
                generation_instruction="And this one?",
                image_path=str(second),
                is_final=True,
            ),
        ],
        input_generator_id="input-gen",
    )

    input_client = MagicMock(spec=ChatAPIClient)
    input_client.chat.side_effect = [
        ChatResponse(content=SYSTEM_TEXT),  # the system prompt (messages[0])
        ChatResponse(content="What is in this image?"),
        ChatResponse(content="What about this one?"),
    ]

    results = _generate(spec, input_client, _target_client())

    assert len(results) == 1
    anchor = results[0]
    assert [m["role"] for m in anchor.messages] == ["system", "user", "assistant", "user"]

    def image_parts(message: dict) -> list[str]:
        content = message["content"]
        if not isinstance(content, list):
            return []
        return [
            part["image"]
            for part in content
            if isinstance(part, dict) and part.get("type") == "image"
        ]

    assert image_parts(anchor.messages[0]) == []  # the system message has no image
    assert image_parts(anchor.messages[1]) == ["images/first.png"]
    assert image_parts(anchor.messages[2]) == []
    assert image_parts(anchor.messages[3]) == ["images/second.png"]
    assert "base64" not in json.dumps(anchor.messages)
    assert anchor.data_source is DataSource.ARD_MULTI


def test_misplaced_system_message_is_refused(tmp_path: Path) -> None:
    """Failure path: an anchor with a trailing system message is not written.

    The anchor is produced by the real generation path (with a system prompt),
    so the record that reaches the gate is the one the pipeline builds; it is
    only the *placement* that is corrupted, which is the failure the shape
    contract exists to catch.
    """
    results = _generate(_spec("minimal_persona"), _input_client(), _target_client())
    assert len(results) == 1
    anchor = results[0]
    anchor.messages.append({"role": "system", "content": "late system"})

    bank = tmp_path / "anchor_bank.jsonl"
    assert append_anchor(anchor, bank) is AppendOutcome.INVALID_SHAPE_SKIPPED
    assert not bank.exists()


def test_off_vocabulary_data_source_is_refused(tmp_path: Path) -> None:
    """Failure path: a record no consumer can route is not written (W-1)."""
